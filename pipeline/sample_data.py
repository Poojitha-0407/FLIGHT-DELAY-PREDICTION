"""Stand-in raw files so the pipeline can be smoke-tested without the download.

Same schemas, a fraction of the rows. Enough to prove the joins, the timezone
handling and the export format. Labels are random -- any model trained on this
is meaningless, which is the point.
"""
from __future__ import annotations

import csv
import datetime as dt
import random
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import AIRPORTS, RAW, YEAR  # noqa: E402

# download.py wipes these before fetching, so a smoke test can't become the
# training set
MARKER = RAW / "SAMPLE_DATA"

BTS_COLUMNS = [
    "Year", "Quarter", "Month", "DayofMonth", "DayOfWeek", "FlightDate",
    "Reporting_Airline", "Tail_Number", "Origin", "Dest", "CRSDepTime", "DepTime",
    "DepDelay", "CRSArrTime", "ArrTime", "ArrDelay", "ArrDelayMinutes",
    "Cancelled", "Diverted", "Distance",
]
CARRIERS = ["AA", "DL", "UA", "WN", "B6", "AS", "NK", "F9"]
FLIGHTS_PER_DAY = 60


def days_in(year: int, month: int) -> int:
    nxt = dt.date(year + 1, 1, 1) if month == 12 else dt.date(year, month + 1, 1)
    return (nxt - dt.date(year, month, 1)).days


def write_bts(year: int) -> None:
    out = RAW / "bts"
    out.mkdir(parents=True, exist_ok=True)
    for month in range(1, 13):
        path = out / f"bts_{year}_{month:02d}.csv"
        with path.open("w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(BTS_COLUMNS)
            for day in range(1, days_in(year, month) + 1):
                date = dt.date(year, month, day)
                for _ in range(FLIGHTS_PER_DAY):
                    origin, dest = random.sample(AIRPORTS, 2)
                    dep_h = random.randint(5, 23)
                    dep_m = random.choice([0, 15, 30, 45])
                    arr = (dep_h * 60 + dep_m + random.randint(60, 330)) % 1440
                    cancelled = int(random.random() < 0.02)
                    diverted = int(random.random() < 0.005)
                    delay = round(max(0.0, random.gauss(8, 35)))
                    w.writerow([
                        year, (month - 1) // 3 + 1, month, day, date.isoweekday(),
                        date.isoformat(), random.choice(CARRIERS), "N123AA",
                        origin, dest, f"{dep_h:02d}{dep_m:02d}", f"{dep_h:02d}{dep_m:02d}",
                        0, f"{arr // 60:02d}{arr % 60:02d}", f"{arr // 60:02d}{arr % 60:02d}",
                        delay, "" if cancelled or diverted else delay,
                        cancelled, diverted, 800,
                    ])
        print(f"  {path.name}")


def write_weather(year: int) -> None:
    out = RAW / "weather"
    out.mkdir(parents=True, exist_ok=True)
    for station in AIRPORTS:
        path = out / f"{station}.csv"
        with path.open("w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["station", "valid", "tmpf", "sknt", "gust", "p01i", "vsby"])
            stamp = dt.datetime(year, 1, 1, 0, 53)
            while stamp.year == year:
                w.writerow([
                    station, stamp.strftime("%Y-%m-%d %H:%M"),
                    round(random.gauss(60, 18), 1),
                    round(abs(random.gauss(8, 5)), 1),
                    "M" if random.random() < 0.8 else round(random.uniform(18, 45), 1),
                    "0.0001" if random.random() < 0.9 else round(random.uniform(0.01, 0.6), 2),
                    random.choice([10, 10, 10, 7, 3, 1, 0.5]),
                ])
                stamp += dt.timedelta(hours=1)
    print(f"  {len(AIRPORTS)} weather stations")


def main() -> None:
    random.seed(7)
    print("Writing stand-in raw data (labels are random - do not read the metrics)")
    for stale in (RAW / "bts", RAW / "weather"):
        if stale.exists():
            shutil.rmtree(stale)
    write_bts(YEAR)
    write_weather(YEAR)
    MARKER.write_text(
        "Generated by pipeline/sample_data.py. Labels are random.\n"
        "`make download` deletes these files before fetching the real ones.\n"
    )
    if not (RAW / "airports.dat").exists():
        print("\nairports.dat is missing. Fetching the real one (it is only 1 MB):")
        import download
        download.download_openflights()


if __name__ == "__main__":
    main()
